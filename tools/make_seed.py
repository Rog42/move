#!/usr/bin/env python3
"""Build seed.sql from a folder of exported JSON docs: <export>/<collection>/<id>.json.

Usage: python3 tools/make_seed.py <export-dir> > seed.sql

- items, rooms and meta/settings are copied as they are.
- meta/counter is dropped; the D1 counters table takes over numbering.
- boxes get an explicit status (old 'arrived' flag -> inroom / labelled), and the
  counter starts after the highest box number so new labels never reuse one.
"""
import json
import sys
import time
from pathlib import Path

STEPS = ["labelled", "packed", "loaded", "inroom"]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main(src: str) -> None:
    root = Path(src)
    now = int(time.time() * 1000)
    rows = []
    top = 0
    for col in ("items", "rooms", "meta", "boxes"):
        folder = root / col
        if not folder.is_dir():
            continue
        for f in sorted(folder.glob("*.json")):
            doc_id = f.stem
            data = json.loads(f.read_text())
            if col == "meta" and doc_id != "settings":
                continue
            if col == "boxes":
                if data.get("status") not in STEPS:
                    data["status"] = "inroom" if data.get("arrived") is True else "labelled"
                data.pop("arrived", None)
                data.pop("createdBy", None)
                data.pop("statusBy", None)
                top = max(top, int(data.get("n") or 0))
            rows.append(f"INSERT OR REPLACE INTO docs (col, id, data, updated_at) VALUES ({q(col)}, {q(doc_id)}, {q(json.dumps(data, ensure_ascii=False, separators=(',', ':')))}, {now});")
    print("-- Generated by tools/make_seed.py. Run after schema.sql.")
    print("\n".join(rows))
    print(f"INSERT INTO counters (k, v) VALUES ('box', {top}) ON CONFLICT (k) DO UPDATE SET v = MAX(v, excluded.v);")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
